"""Write Table 1 (tables/variants.tex) and the validation macros (figures/tikz/validation_values.tex).

Reads only stored results: data/grid/*.json (episode-solver runs) and data/validation/*.json
(copies of the research validation outputs of 8-11 October 2026, plus data/validation/perturbation.json
written by code/checks/perturbation_check.py). Run after code/make_data.py.
"""
import json, glob, math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GRID, VAL = ROOT / "data" / "grid", ROOT / "data" / "validation"
(ROOT / "tables").mkdir(exist_ok=True)


def pct(x):
    return f"{x:.2f}"


def variants_table():
    rows = []
    groups = {}
    for fn in sorted(glob.glob(str(GRID / "variant_*.json"))):
        for r in json.load(open(fn)):
            v = r["variant"]
            if v == "dist":
                key = (1, 0)
                groups[key] = r"$\dot A=|U|$, \ $H=\nu+\eta(1-e^{-A})$"
            elif v == "sq":
                key = (2, 0)
                groups[key] = r"$\dot A=U^2$, \ $H=\nu+\eta(1-e^{-A})$"
            else:
                kap = float(v.split("_")[1])
                key = (3, kap)
                groups[key] = r"$\dot A=|U|$, \ $H=\nu+\eta\,\one\{A>%g\}$" % kap
            rows.append((key, r))
    for lam in (1.0, 2.0):
        g = json.load(open(GRID / f"grid_lam{lam}.json"))
        r = min(g, key=lambda x: (x["SB_fd"] - x["SP_fd"]) / x["SB_fd"])     # largest gap at this pull
        key = (0, r["theta"])
        groups[key] = r"Pausing clock, $\theta=%g$: \ $\dot A=\alpha(U)$, \ $H=\nu+\eta\chi(U)(1-e^{-A})$" % r["theta"]
        rows.append((key, r))
    rows.sort(key=lambda x: (x[0], x[1]["lam"], x[1]["eta"]))
    out = [r"\begin{tabular}{@{}cr@{\hspace{14pt}}cc@{\hspace{14pt}}r@{\hspace{14pt}}r@{}}",
           r"\toprule",
           r"$\lambda$ & $\eta$ & $S_B$ & $S_P$ & $(S_B-S_P)/S_B$, \% & $\Kurt(\Delta)/(6F)$ error, \%\\",
           r"\midrule"]
    last = None
    worst_rel_unc = 0.0
    for key, r in rows:
        if key != last:
            if last is not None:
                out.append(r"\addlinespace[3pt]")
            out.append(r"\multicolumn{6}{@{}l}{%s}\\" % groups[key])
            last = key
        SB, SP = r["SB_fd"], r["SP_fd"]
        gap = 100 * (SB - SP) / SB
        unc = 100 * max(abs(r.get("gap_fd_err_b", 0.0)), abs(r.get("gap_fd_err_t", 0.0))) / SB
        if abs(SB - SP) > 1e-6:
            worst_rel_unc = max(worst_rel_unc, unc / abs(gap))
        kerr = 100 * (r["ALO"] - SB) / SB
        if abs(gap) < 5e-4:
            gap_s = r"$0$"
        else:
            unc_s = r"0.01" if unc < 0.01 else f"{unc:.2f}"
            gap_s = r"$%.2f\pm%s$" % (gap, unc_s)
        kerr_s = r"$0$" if abs(kerr) < 0.05 else r"$%+.0f$" % kerr
        out.append(f"{r['lam']:g} & {r['eta']:g} & {SB:.4f} & {SP:.4f} & {gap_s} & {kerr_s}\\\\")
    out += [r"\bottomrule", r"\end{tabular}"]
    (ROOT / "tables" / "variants.tex").write_text("% Generated by code/make_tables.py; do not edit.\n" + "\n".join(out) + "\n")
    return dict(worst_rel_unc=worst_rel_unc, n=len(rows))


def grid_ratios():
    """Ratio of the kurtosis-statistic error to the unidentified part, and the lambda = 0 controls."""
    out = {}
    for lam in (1.0, 2.0):
        g = json.load(open(GRID / f"grid_lam{lam}.json"))
        rat = [abs((r["ALO"] - r["SB_fd"]) / (r["SB_fd"] - r["SP_fd"])) for r in g]
        out[lam] = (min(rat), max(rat))
    dev = 0.0
    for fn in [GRID / "grid_lam0.0.json"] + sorted(GRID.glob("variant_*lam0.0.json")):
        for r in json.load(open(fn)):
            dev = max(dev, abs(r["SB_fd"] - r["SP_fd"]), abs(r["SB_fd"] - r["VarU"]), abs(r["SB_fd"] - r["ALO"]))
    out["lam0dev"] = dev
    kv = []
    for fn in sorted(GRID.glob("variant_*.json")):
        for r in json.load(open(fn)):
            if r["lam"] > 0:
                kv.append(100 * (r["ALO"] - r["SB_fd"]) / r["SB_fd"])
    out["kerr_other"] = (min(kv), max(kv))
    return out


def grid_errors():
    s_err, gap_rel = 0.0, 0.0
    for fn in sorted(glob.glob(str(GRID / "grid_lam*.json"))):
        for r in json.load(open(fn)):
            s_err = max(s_err, abs(r["SB_fd_err_u"]), abs(r["SB_fd_err_b"]))
            gap = r["SB_fd"] - r["SP_fd"]
            if abs(gap) > 1e-5:
                e = max(abs(r["gap_fd_err_b"]), abs(r["gap_fd_err_t"]))
                gap_rel = max(gap_rel, e / abs(gap))
    return s_err, gap_rel


def validation():
    v = {}
    ctl = json.load(open(VAL / "episode_solver_controls.json"))
    v["ValCtlN"] = len(ctl)
    v["ValCtlErr"] = max(max(abs(c["num"]["SB_fd"] - c["exact"]["S"]), abs(c["num"]["SB_formula"] - c["exact"]["S"]))
                         for c in ctl)
    v["ValCtlLamZeroGap"] = max(abs(c["num"]["gap_fd"]) for c in ctl if c["lam"] == 0)
    st = json.load(open(VAL / "stationary_solver_renewal_limit.json"))
    v["ValStatRenewalErr"] = max(abs(e["extrap"]["S_res"]["extrap"] - e["ref"]["S"]) for e in st)
    bench = [e for e in json.load(open(VAL / "stationary_solver_benchmark.json")) if e["name"].startswith("BENCH")][0]
    v["ValBenchStat"] = bench["extrap"]["S_res"]["extrap"]
    v["ValBenchStatErr"] = bench["extrap"]["S_res"]["err_est"]
    mc = json.load(open(VAL / "mc_benchmark.json"))
    pde, run = mc["pde"], mc["runs"][0]
    v.update(ValBenchSB=pde["SB_formula"], ValBenchSP=pde["SP_formula"], ValBenchGap=pde["gap_formula"],
             ValMCSB=run["S_fd_B"], ValMCSBse=run["se_S_fd_B"], ValMCSP=run["S_fd_P"], ValMCSPse=run["se_S_fd_P"],
             ValMCGap=run["gap_fd"], ValMCGapse=run["se_gap_fd"], ValMCPaths=mc["npaths"], ValMCdt=run["dt"],
             ValMCDistZ=max(run["dist"][k]["max_z_BminusP"] for k in ("dur", "rev", "occ")))
    ident = json.load(open(VAL / "record_identity.json"))
    v["ValIdentN"] = len(ident)
    v["ValIdentMax"] = max(max(max(x.values()) for x in e["identity"].values()) for e in ident)
    km = json.load(open(VAL / "kernel_mc_comparison.json"))
    v["ValKernelRmsZ"] = max(d["rms_z"] for d in km.values())
    v["ValKernelN"] = len(km)
    ic = VAL / "identity_checks.json"
    if ic.exists():
        icd = json.load(open(ic))
        v["ValFRmc"] = icd["fluct_response_calvo"]["mc"]
        v["ValFRse"] = icd["fluct_response_calvo"]["se"]
        v["ValFRexact"] = icd["fluct_response_calvo"]["exact"]
        v["ValFRT"] = icd["fluct_response_calvo"]["T"]
        v["ValFRpaths"] = icd["fluct_response_calvo"]["N"]
    rr = VAL / "running_refinement.json"
    if rr.exists():
        v["ValRunStatExtrap"] = json.load(open(rr))["S_extrap_Na"]
    p = VAL / "perturbation.json"
    if p.exists():
        pt = json.load(open(p))
        v.update(ValPertPred=pt["prediction"], ValPertMC=pt["mc_derivative"], ValPertSE=pt["mc_se"],
                 ValPertPaths=pt["N"], ValPertEps=pt["eps"])
    return v


if __name__ == "__main__":
    tab = variants_table()
    s_err, gap_rel = grid_errors()
    v = validation()
    fmt = {
        "ValCtlN": "{:d}", "ValCtlErr": "{:.0e}", "ValCtlLamZeroGap": "{:.0e}", "ValStatRenewalErr": "{:.0e}",
        "ValBenchStat": "{:.7f}", "ValBenchStatErr": "{:.0e}", "ValBenchSB": "{:.7f}", "ValBenchSP": "{:.6f}",
        "ValBenchGap": "{:.5f}", "ValMCSB": "{:.5f}", "ValMCSBse": "{:.5f}", "ValMCSP": "{:.5f}", "ValMCSPse": "{:.5f}",
        "ValMCGap": "{:.5f}", "ValMCGapse": "{:.5f}", "ValMCPaths": "{:,d}", "ValMCdt": "{:g}", "ValMCDistZ": "{:.1f}",
        "ValIdentN": "{:d}", "ValIdentMax": "{:.0e}", "ValKernelRmsZ": "{:.1f}", "ValKernelN": "{:d}",
        "ValRunStatExtrap": "{:.4f}", "ValFRmc": "{:.4f}", "ValFRse": "{:.4f}", "ValFRexact": "{:.4f}",
        "ValFRT": "{:g}", "ValFRpaths": "{:,d}", "ValPertPred": "{:.4f}", "ValPertMC": "{:.4f}", "ValPertSE": "{:.4f}", "ValPertPaths": "{:,d}", "ValPertEps": "{:g}",
    }
    lines = ["% Generated by code/make_tables.py; do not edit."]
    for k, val in v.items():
        s = fmt[k].format(val).replace(",", "{,}")
        if "e-" in s:                                   # 3e-15 -> 3\times10^{-15}
            m, e = s.split("e-")
            s = (f"{m}\\times10^{{-{int(e)}}}" if m != "1" else f"10^{{-{int(e)}}}")
        lines.append(r"\def\%s{%s}" % (k, s))
    lines.append(r"\def\GridSerr{%s}" % (f"{s_err:.0e}".replace("e-0", r"\times10^{-") + "}"))
    lines.append(r"\def\GridGapRelErr{%.1f}" % (100 * gap_rel))
    lines.append(r"\def\TabGapRelUnc{%.0f}" % (100 * tab["worst_rel_unc"]))
    rt = grid_ratios()
    lines.append(r"\def\MagRatioOneMin{%.0f}" % rt[1.0][0])
    lines.append(r"\def\MagRatioOneMax{%.0f}" % rt[1.0][1])
    lines.append(r"\def\MagRatioTwoMin{%.0f}" % rt[2.0][0])
    lines.append(r"\def\MagKerrOtherMin{%.0f}" % rt["kerr_other"][0])
    lines.append(r"\def\MagKerrOtherMax{%.0f}" % rt["kerr_other"][1])
    lines.append(r"\def\MagLamZeroDev{%s}" % (f"{rt['lam0dev']:.0e}".replace("e-0", r"\times10^{-") + "}"))
    (ROOT / "figures" / "tikz" / "validation_values.tex").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
