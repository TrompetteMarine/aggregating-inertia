//! Table S1.1 (tex/variants.tex) and the validation macros (tex/validation_values.tex): port of
//! `make_tables.py`. Reads only stored results.

use super::{f, py_thousands, read_json, Paths};
use crate::util::py_exp;
use anyhow::Result;
use serde_json::Value;

fn grid_rows(p: &Paths, prefix: &str) -> Result<Vec<(String, Vec<Value>)>> {
    let mut files: Vec<_> = std::fs::read_dir(p.grid())?.filter_map(|e| e.ok()).map(|e| e.path()).collect();
    files.sort();
    let mut out = vec![];
    for fname in files {
        let name = fname.file_name().unwrap().to_string_lossy().to_string();
        if name.starts_with(prefix) && name.ends_with(".json") {
            out.push((name, read_json(&fname)?.as_array().unwrap().clone()));
        }
    }
    Ok(out)
}

/// Table S1.1 of the Supplement; returns the worst relative uncertainty of the gaps.
pub fn variants_table(p: &Paths) -> Result<(f64, usize)> {
    // key: (group, kappa) -> heading
    let mut rows: Vec<((i32, f64), Value)> = vec![];
    let mut groups: Vec<((i32, f64), String)> = vec![];
    let mut set_group = |key: (i32, f64), s: String| {
        if !groups.iter().any(|(k, _)| *k == key) {
            groups.push((key, s));
        }
    };
    for (_, list) in grid_rows(p, "variant_")? {
        for r in list {
            let v = r["variant"].as_str().unwrap().to_string();
            let key = if v == "dist" {
                set_group((1, 0.0), r"$\dot A=|U|$, \ $H=\nu+\eta(1-e^{-A})$".into());
                (1, 0.0)
            } else if v == "sq" {
                set_group((2, 0.0), r"$\dot A=U^2$, \ $H=\nu+\eta(1-e^{-A})$".into());
                (2, 0.0)
            } else {
                let kap: f64 = v.split('_').nth(1).unwrap().parse().unwrap();
                set_group((3, kap), format!(r"$\dot A=|U|$, \ $H=\nu+\eta\,\one\{{A>{}\}}$", super::py_g(kap)));
                (3, kap)
            };
            rows.push((key, r));
        }
    }
    for lam in ["1.0", "2.0"] {
        let g = read_json(&p.grid().join(format!("grid_lam{lam}.json")))?;
        let r = g
            .as_array()
            .unwrap()
            .iter()
            .min_by(|a, b| {
                let ga = (f(a, "SB_fd") - f(a, "SP_fd")) / f(a, "SB_fd");
                let gb = (f(b, "SB_fd") - f(b, "SP_fd")) / f(b, "SB_fd");
                ga.partial_cmp(&gb).unwrap()
            })
            .unwrap()
            .clone();
        let key = (0, f(&r, "theta"));
        set_group(key, format!(r"Pausing clock, $\theta={}$: \ $\dot A=\alpha(U)$, \ $H=\nu+\eta\chi(U)(1-e^{{-A}})$", super::py_g(f(&r, "theta"))));
        rows.push((key, r));
    }
    rows.sort_by(|a, b| {
        (a.0 .0, a.0 .1, f(&a.1, "lam"), f(&a.1, "eta")).partial_cmp(&(b.0 .0, b.0 .1, f(&b.1, "lam"), f(&b.1, "eta"))).unwrap()
    });
    let mut out = vec![
        r"\begin{tabular}{@{}cr@{\hspace{14pt}}cc@{\hspace{14pt}}r@{\hspace{14pt}}r@{}}".to_string(),
        r"\toprule".into(),
        r"$\lambda$ & $\eta$ & $S_B$ & $S_P$ & $(S_B-S_P)/S_B$, \% & $\Kurt(\Delta)/(6F)$ error, \%\\".into(),
        r"\midrule".into(),
    ];
    let mut last: Option<(i32, f64)> = None;
    let mut worst: f64 = 0.0;
    for (key, r) in &rows {
        if last != Some(*key) {
            if last.is_some() {
                out.push(r"\addlinespace[3pt]".into());
            }
            let head = &groups.iter().find(|(k, _)| k == key).unwrap().1;
            out.push(format!(r"\multicolumn{{6}}{{@{{}}l}}{{{head}}}\\"));
            last = Some(*key);
        }
        let (sb, sp) = (f(r, "SB_fd"), f(r, "SP_fd"));
        let gap = 100.0 * (sb - sp) / sb;
        let eb = r.get("gap_fd_err_b").and_then(|x| x.as_f64()).unwrap_or(0.0).abs();
        let et = r.get("gap_fd_err_t").and_then(|x| x.as_f64()).unwrap_or(0.0).abs();
        let unc = 100.0 * eb.max(et) / sb;
        if (sb - sp).abs() > 1e-6 {
            worst = worst.max(unc / gap.abs());
        }
        let kerr = 100.0 * (f(r, "ALO") - sb) / sb;
        let gap_s = if gap.abs() < 5e-4 {
            "$0$".to_string()
        } else {
            let unc_s = if unc < 0.01 { "0.01".to_string() } else { format!("{unc:.2}") };
            format!("${gap:.2}\\pm{unc_s}$")
        };
        let kerr_s = if kerr.abs() < 0.05 { "$0$".to_string() } else { format!("${:+.0}$", kerr) };
        out.push(format!("{} & {} & {:.4} & {:.4} & {} & {}\\\\", super::py_g(f(r, "lam")), super::py_g(f(r, "eta")), sb, sp, gap_s, kerr_s));
    }
    out.push(r"\bottomrule".into());
    out.push(r"\end{tabular}".into());
    std::fs::write(p.tex().join("variants.tex"), format!("% Generated by inertia (Rust port of code/make_tables.py); do not edit.\n{}\n", out.join("\n")))?;
    Ok((worst, rows.len()))
}

fn grid_errors(p: &Paths) -> Result<(f64, f64)> {
    let (mut s_err, mut gap_rel): (f64, f64) = (0.0, 0.0);
    for (_, list) in grid_rows(p, "grid_lam")? {
        for r in list {
            s_err = s_err.max(f(&r, "SB_fd_err_u").abs()).max(f(&r, "SB_fd_err_b").abs());
            let gap = f(&r, "SB_fd") - f(&r, "SP_fd");
            if gap.abs() > 1e-5 {
                let e = f(&r, "gap_fd_err_b").abs().max(f(&r, "gap_fd_err_t").abs());
                gap_rel = gap_rel.max(e / gap.abs());
            }
        }
    }
    Ok((s_err, gap_rel))
}

fn grid_ratios(p: &Paths) -> Result<Vec<(String, f64)>> {
    let mut out = vec![];
    for lam in ["1.0", "2.0"] {
        let g = read_json(&p.grid().join(format!("grid_lam{lam}.json")))?;
        let rat: Vec<f64> = g.as_array().unwrap().iter().map(|r| ((f(r, "ALO") - f(r, "SB_fd")) / (f(r, "SB_fd") - f(r, "SP_fd"))).abs()).collect();
        out.push((format!("{lam}min"), crate::util::min_of(&rat)));
        out.push((format!("{lam}max"), crate::util::max_of(&rat)));
    }
    let mut dev: f64 = 0.0;
    let mut lam0 = vec![p.grid().join("grid_lam0.0.json")];
    for (name, _) in grid_rows(p, "variant_")? {
        if name.ends_with("lam0.0.json") {
            lam0.push(p.grid().join(name));
        }
    }
    for fname in lam0 {
        for r in read_json(&fname)?.as_array().unwrap() {
            dev = dev.max((f(r, "SB_fd") - f(r, "SP_fd")).abs()).max((f(r, "SB_fd") - f(r, "VarU")).abs()).max((f(r, "SB_fd") - f(r, "ALO")).abs());
        }
    }
    out.push(("lam0dev".into(), dev));
    let mut kv = vec![];
    for (_, list) in grid_rows(p, "variant_")? {
        for r in list {
            if f(&r, "lam") > 0.0 {
                kv.push(100.0 * (f(&r, "ALO") - f(&r, "SB_fd")) / f(&r, "SB_fd"));
            }
        }
    }
    out.push(("kerr_min".into(), crate::util::min_of(&kv)));
    out.push(("kerr_max".into(), crate::util::max_of(&kv)));
    Ok(out)
}

/// "{:.0e}"-style macro with the make_tables conversion 3e-15 -> 3\times10^{-15}, 1e-8 -> 10^{-8}.
fn sci_macro(x: f64) -> String {
    let s = py_exp(x, 0);
    if let Some((m, e)) = s.split_once("e-") {
        let ev: i32 = e.parse().unwrap();
        if m != "1" { format!("{m}\\times10^{{-{ev}}}") } else { format!("10^{{-{ev}}}") }
    } else {
        s
    }
}

/// The reference's GridSerr/MagLamZeroDev conversion: "{:.0e}".replace("e-0", "\times10^{-") + "}".
fn sci_replace(x: f64) -> String {
    py_exp(x, 0).replace("e-0", r"\times10^{-") + "}"
}

pub fn run_all(p: &Paths) -> Result<()> {
    let (worst, _n) = variants_table(p)?;
    let (s_err, gap_rel) = grid_errors(p)?;
    let val = p.validation();
    let mut lines = vec!["% Generated by inertia (Rust port of code/make_tables.py); do not edit.".to_string()];
    let mut push = |k: &str, s: String| lines.push(format!("\\def\\{k}{{{s}}}"));
    let ctl = read_json(&val.join("episode_solver_controls.json"))?;
    let ctl = ctl.as_array().unwrap();
    push("ValCtlN", format!("{}", ctl.len()));
    let cerr = ctl.iter().map(|c| (f(&c["num"], "SB_fd") - f(&c["exact"], "S")).abs().max((f(&c["num"], "SB_formula") - f(&c["exact"], "S")).abs())).fold(0.0, f64::max);
    push("ValCtlErr", sci_macro(cerr));
    let lz = ctl.iter().filter(|c| f(c, "lam") == 0.0).map(|c| f(&c["num"], "gap_fd").abs()).fold(0.0, f64::max);
    push("ValCtlLamZeroGap", sci_macro(lz));
    let st = read_json(&val.join("stationary_solver_renewal_limit.json"))?;
    let rerr = st.as_array().unwrap().iter().map(|e| (f(&e["extrap"]["S_res"], "extrap") - f(&e["ref"], "S")).abs()).fold(0.0, f64::max);
    push("ValStatRenewalErr", sci_macro(rerr));
    let bench_all = read_json(&val.join("stationary_solver_benchmark.json"))?;
    let bench = bench_all.as_array().unwrap().iter().find(|e| e["name"].as_str().unwrap().starts_with("BENCH")).unwrap();
    push("ValBenchStat", format!("{:.7}", f(&bench["extrap"]["S_res"], "extrap")));
    push("ValBenchStatErr", sci_macro(f(&bench["extrap"]["S_res"], "err_est")));
    let mc = read_json(&val.join("mc_benchmark.json"))?;
    let (pde, run) = (&mc["pde"], &mc["runs"][0]);
    push("ValBenchSB", format!("{:.7}", f(pde, "SB_formula")));
    push("ValBenchSP", format!("{:.6}", f(pde, "SP_formula")));
    push("ValBenchGap", format!("{:.5}", f(pde, "gap_formula")));
    push("ValMCSB", format!("{:.5}", f(run, "S_fd_B")));
    push("ValMCSBse", format!("{:.5}", f(run, "se_S_fd_B")));
    push("ValMCSP", format!("{:.5}", f(run, "S_fd_P")));
    push("ValMCSPse", format!("{:.5}", f(run, "se_S_fd_P")));
    push("ValMCGap", format!("{:.5}", f(run, "gap_fd")));
    push("ValMCGapse", format!("{:.5}", f(run, "se_gap_fd")));
    push("ValMCPaths", py_thousands(mc["npaths"].as_u64().unwrap()).replace(',', "{,}"));
    push("ValMCdt", super::py_g(f(run, "dt")));
    let dz = ["dur", "rev", "occ"].iter().map(|k| f(&run["dist"][*k], "max_z_BminusP")).fold(0.0, f64::max);
    push("ValMCDistZ", format!("{dz:.1}"));
    let ident = read_json(&val.join("record_identity.json"))?;
    let ident = ident.as_array().unwrap();
    push("ValIdentN", format!("{}", ident.len()));
    let imax = ident
        .iter()
        .flat_map(|e| e["identity"].as_object().unwrap().values().flat_map(|x| x.as_object().unwrap().values().map(|v| v.as_f64().unwrap()).collect::<Vec<_>>()))
        .fold(0.0, f64::max);
    push("ValIdentMax", sci_macro(imax));
    let km = read_json(&val.join("kernel_mc_comparison.json"))?;
    let km = km.as_object().unwrap();
    push("ValKernelRmsZ", format!("{:.1}", km.values().map(|d| f(d, "rms_z")).fold(0.0, f64::max)));
    push("ValKernelN", format!("{}", km.len()));
    let ic = read_json(&val.join("identity_checks.json"))?;
    let fr = &ic["fluct_response_calvo"];
    push("ValFRmc", format!("{:.4}", f(fr, "mc")));
    push("ValFRse", format!("{:.4}", f(fr, "se")));
    push("ValFRexact", format!("{:.4}", f(fr, "exact")));
    push("ValFRT", super::py_g(f(fr, "T")));
    push("ValFRpaths", py_thousands(fr["N"].as_u64().unwrap()).replace(',', "{,}"));
    let rr = read_json(&val.join("running_refinement.json"))?;
    push("ValRunStatExtrap", format!("{:.4}", f(&rr, "S_extrap_Na")));
    let pt = read_json(&val.join("perturbation.json"))?;
    push("ValPertPred", format!("{:.4}", f(&pt, "prediction")));
    push("ValPertMC", format!("{:.4}", f(&pt, "mc_derivative")));
    push("ValPertSE", format!("{:.4}", f(&pt, "mc_se")));
    push("ValPertPaths", py_thousands(pt["N"].as_u64().unwrap()).replace(',', "{,}"));
    push("ValPertEps", super::py_g(f(&pt, "eps")));
    push("GridSerr", sci_replace(s_err));
    push("GridGapRelErr", format!("{:.1}", 100.0 * gap_rel));
    push("TabGapRelUnc", format!("{:.0}", 100.0 * worst));
    let rt = grid_ratios(p)?;
    let g = |k: &str| rt.iter().find(|(n, _)| n == k).unwrap().1;
    push("MagRatioOneMin", format!("{:.0}", g("1.0min")));
    push("MagRatioOneMax", format!("{:.0}", g("1.0max")));
    push("MagRatioTwoMin", format!("{:.0}", g("2.0min")));
    push("MagKerrOtherMin", format!("{:.0}", g("kerr_min")));
    push("MagKerrOtherMax", format!("{:.0}", g("kerr_max")));
    push("MagLamZeroDev", sci_replace(g("lam0dev")));
    std::fs::write(p.tex().join("validation_values.tex"), lines.join("\n") + "\n")?;
    Ok(())
}
